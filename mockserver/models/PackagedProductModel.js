class PackagedProduct {
  constructor(
    productId,
    productName,
    itemNumber,
    imageUrl,
    quantity,
    unitPrice,
  ) {
    this.productId = productId;
    this.productName = productName;
    this.itemNumber = itemNumber;
    this.imageUrl = imageUrl;
    this.quantity = quantity;
    this.unitPrice = unitPrice;
  }
}

export default PackagedProduct;
